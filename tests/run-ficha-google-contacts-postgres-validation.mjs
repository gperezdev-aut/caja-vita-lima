import { existsSync } from "node:fs";
import { basename, dirname, resolve } from "node:path";
import { spawnSync } from "node:child_process";
import { randomUUID } from "node:crypto";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const migration = resolve(root, "sql/041_ficha_google_contacts_outbox.sql");
const contract = resolve(root, "sql/QA_FICHA_GOOGLE_CONTACTS_OUTBOX_ROLLBACK.sql");
const files = [migration, contract];

const setupSql = `
create schema if not exists extensions;
do $$ begin
  if not exists(select 1 from pg_roles where rolname='anon') then create role anon nologin; end if;
  if not exists(select 1 from pg_roles where rolname='authenticated') then create role authenticated nologin; end if;
  if not exists(select 1 from pg_roles where rolname='service_role') then create role service_role nologin; end if;
end $$;

create table public.clientes (
  cliente_id text primary key,
  cliente text,
  whatsapp_e164 text,
  email text,
  fecha_nacimiento date,
  telefono_estado text
);

create table public.cliente_contact_sync_outbox (
  sync_id bigint generated by default as identity primary key,
  cliente_id text not null,
  provider text not null default 'GOOGLE_CONTACTS',
  estado text not null default 'PENDING',
  payload_hash text not null,
  resource_name text,
  attempts integer not null default 0,
  processing_token text,
  lease_until timestamptz,
  next_retry_at timestamptz,
  last_error text,
  last_synced_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (cliente_id, provider)
);

create table public.citas_reservadas (
  reserva_id text primary key,
  cliente_id text,
  estado_ficha text
);
`;

function fail(message) {
  throw new Error(message);
}

function run(command, args, capture = false) {
  const result = spawnSync(command, args, {
    cwd: root,
    encoding: capture ? "utf8" : undefined,
    stdio: capture ? ["ignore", "pipe", "inherit"] : "inherit",
  });
  if (result.error || result.status !== 0) {
    fail(`${command} failed validating ficha -> Google Contacts outbox`);
  }
  return result.stdout?.trim();
}

for (const file of files) {
  if (!existsSync(file)) fail(`Required SQL file not found: ${file}`);
}

async function docker() {
  run("docker", ["info", "--format", "{{.ServerVersion}}"]);
  const name = `caja-ficha-gc-${randomUUID().replaceAll("-", "").slice(0, 12)}`;
  let created = false;
  try {
    run("docker", [
      "run", "--detach", "--rm", "--name", name,
      "--env", "POSTGRES_DB=contract",
      "--env", "POSTGRES_USER=contract",
      "--env", "POSTGRES_PASSWORD=contract",
      "postgres:16-alpine",
    ], true);
    created = true;

    for (let i = 0; i < 30; i += 1) {
      const ready = spawnSync("docker", [
        "exec", name, "pg_isready", "-U", "contract", "-d", "contract",
      ], { stdio: "ignore" });
      if (ready.status === 0) break;
      if (i === 29) fail("PostgreSQL did not become ready");
      await new Promise((r) => setTimeout(r, 1000));
    }

    const prefix = ["exec", name, "psql", "-U", "contract", "-d", "contract"];
    run("docker", [...prefix, "-v", "ON_ERROR_STOP=1", "-c", setupSql]);
    run("docker", ["exec", name, "mkdir", "-p", "/validation"]);

    for (const file of files) {
      const target = `/validation/${basename(file)}`;
      run("docker", ["cp", file, `${name}:${target}`]);
      run("docker", [...prefix, "-v", "ON_ERROR_STOP=1", "-f", target]);
    }
  } finally {
    if (created) spawnSync("docker", ["rm", "--force", name], { stdio: "ignore" });
  }
}

if (process.env.DATABASE_URL) {
  const prefix = ["--dbname", process.env.DATABASE_URL, "-v", "ON_ERROR_STOP=1"];
  run("psql", [...prefix, "-c", setupSql]);
  for (const file of files) run("psql", [...prefix, "-f", file]);
} else {
  await docker();
}

