  movimiento_id text primary key,
  fecha date,
  hora time,
  sede text,
  tipo_movimiento text,
  estado text default 'Registrado',
  cliente_id text,
  cliente text,
  whatsapp text,
  dni text,
  n_pax integer default 1,
  servicio text,
  duracion text,
