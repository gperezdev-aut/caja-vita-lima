-- 12) VISTAS INICIALES
-- Estas vistas ayudan a la futura app y al dashboard.
-- ============================================================

create or replace view public.vista_citas_con_cliente as
select
  c.*,
  cl.total_reservas,
  cl.segmento_cliente,
  cl.cliente_potencial,
  cl.primera_reserva,
  cl.ultima_reserva,
  cl.ultima_visita,
  cl.ultimo_servicio,
  cl.ultima_sede
from public.citas_reservadas c
left join public.clientes cl
  on cl.cliente_id = c.cliente_id;

create or replace view public.vista_movimientos_dashboard as
select
  m.movimiento_id,
  m.fecha,
  m.hora,
  m.sede,
  m.tipo_movimiento,
  m.estado,
  m.cliente_id,
  m.cliente,
  m.whatsapp,
  m.dni,
  m.n_pax,
  m.servicio,
  m.duracion,
  m.monto_servicio,
  m.adelanto_prev,
  m.total_cobrar,
  m.total_pagado,
  m.total_extras,
  m.pendiente,
  m.estado_boleta,
  m.numero_boleta,
  m.responsable,
  m.source_type,
  m.source_id,
  m.created_at,
  m.updated_at
from public.caja_movimientos m;

