-- Recomendado para UUID si más adelante usamos ids automáticos.
create extension if not exists "pgcrypto";

-- ============================================================
-- 1) CONFIG_LISTAS
-- Equivalente a hoja: CONFIG_LISTAS
-- ============================================================
create table if not exists public.config_listas (
  id bigint generated by default as identity primary key,
  lista text not null,
  valor text not null,
  orden integer,
  activo boolean default true,
  alias_de text,
  nota text,
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);

create index if not exists idx_config_listas_lista on public.config_listas(lista);
create index if not exists idx_config_listas_activo on public.config_listas(activo);

-- ============================================================
-- 2) USUARIOS
-- Equivalente a hoja: USUARIOS
-- Nota: en una fase posterior el login real debe pasar a Supabase Auth.
-- ============================================================
create table if not exists public.usuarios (
  id bigint generated by default as identity primary key,
  usuario text unique not null,
  pin text,
  rol text not null,
  nombre text,
  activo boolean default true,
  nota text,
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);

create index if not exists idx_usuarios_rol on public.usuarios(rol);
create index if not exists idx_usuarios_activo on public.usuarios(activo);

-- ============================================================
-- 3) CLIENTES
-- Equivalente a hoja: CLIENTES
-- ============================================================
create table if not exists public.clientes (
  cliente_id text primary key,
  cliente text,
  whatsapp text,
  dni text,
  email text,
  ultima_sede text,
  ultima_visita date,
  ultimo_servicio text,
  notas text,
  origen text,
  created_at timestamptz default now(),
  updated_at timestamptz default now(),
  total_reservas integer default 0,
  primera_reserva date,
  ultima_reserva date,
  cliente_potencial text,
  segmento_cliente text
);

create index if not exists idx_clientes_whatsapp on public.clientes(whatsapp);
create index if not exists idx_clientes_dni on public.clientes(dni);
create index if not exists idx_clientes_cliente on public.clientes(cliente);
create index if not exists idx_clientes_segmento on public.clientes(segmento_cliente);

-- ============================================================
-- 4) CITAS_RESERVADAS
-- Equivalente a hoja: CITAS_RESERVADAS
-- ============================================================
create table if not exists public.citas_reservadas (
  reserva_id text primary key,
  fecha_cita date,
  hora_cita time,
  sede text,
  cliente_id text,
  cliente text,
  dni text,
  whatsapp text,
  n_pax integer default 1,
  servicio text,
  duracion text,
  monto_total numeric(12,2) default 0,
  adelanto numeric(12,2) default 0,
  metodo_adelanto text,
  saldo_pendiente numeric(12,2) default 0,
  estado text default 'PENDIENTE',
  source text,
  source_id text,
  service_code text,
  servicio_detalle text,
  calendar_description text,
  calendar_status text,
  calendar_event_id text,
  calendar_link text,
  calendar_error text,
  calendar_created_at timestamptz,
  observacion text,
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);

create index if not exists idx_citas_fecha on public.citas_reservadas(fecha_cita);
create index if not exists idx_citas_sede on public.citas_reservadas(sede);
create index if not exists idx_citas_estado on public.citas_reservadas(estado);
create index if not exists idx_citas_cliente_id on public.citas_reservadas(cliente_id);
create index if not exists idx_citas_whatsapp on public.citas_reservadas(whatsapp);
create index if not exists idx_citas_calendar_event_id on public.citas_reservadas(calendar_event_id);

-- ============================================================
-- 5) CAJA_MOVIMIENTOS
