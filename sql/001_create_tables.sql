create index if not exists idx_mov_fecha on public.caja_movimientos(fecha);
create index if not exists idx_mov_sede on public.caja_movimientos(sede);
create index if not exists idx_mov_tipo on public.caja_movimientos(tipo_movimiento);
create index if not exists idx_mov_cliente_id on public.caja_movimientos(cliente_id);
create index if not exists idx_mov_whatsapp on public.caja_movimientos(whatsapp);
create index if not exists idx_mov_estado_boleta on public.caja_movimientos(estado_boleta);
create index if not exists idx_mov_source on public.caja_movimientos(source_type, source_id);

